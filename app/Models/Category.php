<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class Category extends Model
{
    /*
    |--------------------------------------------------------------------------
    | TABLE
    |--------------------------------------------------------------------------
    */

    protected $table = 'categories';

    /*
    |--------------------------------------------------------------------------
    | FILLABLE
    |--------------------------------------------------------------------------
    */

    protected $fillable = [

        'name',
        'slug',
    ];

    /*
    |--------------------------------------------------------------------------
    | SUB CATEGORIES
    |--------------------------------------------------------------------------
    */

    public function subCategories()
    {
        return $this->hasMany(
            SubCategory::class,
            'category_id'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | ITEMS
    |--------------------------------------------------------------------------
    */

    public function items()
    {
        return $this->hasMany(
            Item::class,
            'category_id'
        );
    }
}